import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.ksp)
    alias(libs.plugins.room)
}

// CI passes these in; local builds fall back to dev values.
val ciVersionCode = providers.environmentVariable("VERSION_CODE").orNull?.toInt() ?: 1
val ciVersionName = providers.environmentVariable("VERSION_NAME").orNull ?: "0.0.0-dev.local"

// Release signing comes from the environment (GitHub Actions secrets). Without it, the
// release APK is left unsigned, which is fine for local builds.
val signingStoreFile = providers.environmentVariable("SIGNING_STORE_FILE").orNull
val hasReleaseSigning = signingStoreFile != null

android {
    namespace = "com.vishwesh.slottracker"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.vishwesh.slottracker"
        minSdk = 31
        targetSdk = 37
        versionCode = ciVersionCode
        versionName = ciVersionName
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = file(signingStoreFile!!)
                storePassword = providers.environmentVariable("SIGNING_STORE_PASSWORD").get()
                keyAlias = providers.environmentVariable("SIGNING_KEY_ALIAS").get()
                keyPassword = providers.environmentVariable("SIGNING_KEY_PASSWORD").get()
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (hasReleaseSigning) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_17
    }
}

